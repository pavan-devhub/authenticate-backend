CREATE TABLE login_attempts (
    id           BIGINT                      GENERATED BY DEFAULT AS IDENTITY,
    user_id      BIGINT                      NOT NULL,
    successful   BOOLEAN                     NOT NULL,
    attempted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT fk_login_attempts_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE INDEX idx_login_attempts_user_time ON login_attempts (user_id, attempted_at);
